# Built from the packaging machine at run time so this file itself names no person.
import getpass,os
PATTERNS=sorted({s.encode() for s in (getpass.getuser(),Path.home().name,os.environ.get('USERNAME',''),os.environ.get('USERDOMAIN','')) if len(s)>=3}
                |{b'C:'+s for s in (b'\\Users\\',b'/Users/')}|{b'\\AppData'+b'\\Local\\Temp\\'})

def personal_hits(data):
    hits=[]
    for p in PATTERNS:
        for form in (p,p.decode().encode('utf-16-le')):
            if form.lower() in data.lower():hits.append(p.decode())
    return sorted(set(hits))

def exe_payload(exe):
    """Yields (name, bytes) for every file inside the PyInstaller archive, decompressed."""
    from PyInstaller.archive.readers import CArchiveReader
    arch=CArchiveReader(str(exe))
    for name in arch.toc:
        data=arch.extract(name)
        yield name,data or b''
        if name.endswith('.pyz') or arch.toc[name][-1]=='z':
            pyz=arch.open_embedded_archive(name)
            for mod in pyz.toc:yield name+'/'+mod,pyz.extract(mod,raw=True) or b''

def main(build,shots,out,tutorial=None):
    build,shots,out=Path(build),Path(shots),Path(out);report={'version':VERSION,'checks':{}}
    stage_root=Path(tempfile.mkdtemp(prefix='presetdesk-pkg-'));stage=stage_root/NAME
    (stage/'source').mkdir(parents=True);(stage/'licenses').mkdir();(stage/'screenshots').mkdir()
    shutil.copy2(build/'dist'/'Tune.exe',stage/'Tune.exe')
    shutil.copy2(HERE/'README-v4.0.txt',stage/'README.txt');shutil.copy2(HERE/'VERIFICATION-v4.0.txt',stage/'VERIFICATION.txt')
    shutil.copy2(build/'exe-selftest.json',stage/'exe-selftest.json')
    (stage/'THIRD-PARTY-NOTICES.txt').write_text(NOTICES,encoding='utf-8')
    for name,src in LICENSES.items():shutil.copy2(src,stage/'licenses'/name)
    import PyInstaller;dist=Path(PyInstaller.__file__).parent.parent/'pyinstaller-6.22.3.dist-info'/'licenses'/'COPYING.txt'
    shutil.copy2(dist,stage/'licenses'/'PyInstaller-COPYING.txt')
    for f in SOURCE:shutil.copy2(HERE/f,stage/'source'/f)
    shutil.copy2(HERE/'README-v4.0.txt',stage/'source'/'README.txt')
    for png in sorted(shots.glob('*.png')):shutil.copy2(png,stage/'screenshots'/png.name)
    if tutorial:shutil.copy2(tutorial,stage/'tutorial-15s.mp4')
    # 1. personal-data scan over every staged file and the unpacked EXE payload
    hits={}
    for f in stage.rglob('*'):
        if f.is_file() and f.name!='Tune.exe':
            h=personal_hits(f.read_bytes())
            if h:hits[str(f.relative_to(stage))]=h
    inner=0
    for name,data in exe_payload(stage/'Tune.exe'):
        inner+=1;h=personal_hits(data)
        if h:hits['Tune.exe!'+name]=h
    report['checks']['personal_data_scan']={'files':sum(1 for f in stage.rglob('*') if f.is_file()),'exe_inner_entries':inner,'hits':hits,'result':'PASS' if not hits else 'FAIL'}
    report['checks']['no_profiles_or_backups']='PASS' if not any(p.suffix=='.json' and p.name!='exe-selftest.json' for p in stage.rglob('*')) else 'FAIL'
    # 2. shipped source passes its own tests in isolation
    with tempfile.TemporaryDirectory(prefix='presetdesk-src-') as t:
        shutil.copytree(stage/'source',Path(t)/'source')
        r=subprocess.run([sys.executable,'-m','unittest','test_capture','test_reference','test_desk'],cwd=Path(t)/'source',capture_output=True,text=True)
        report['checks']['source_tests']={'result':'PASS' if r.returncode==0 else 'FAIL','summary':r.stderr.strip().splitlines()[-3:]}
    # 3. zip, re-open and compare, checksum
    out.mkdir(parents=True,exist_ok=True);zpath=out/(NAME+'.zip')
    with zipfile.ZipFile(zpath,'w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for f in sorted(stage.rglob('*')):
            if f.is_file():z.write(f,f.relative_to(stage_root).as_posix())
    with zipfile.ZipFile(zpath) as z:
        bad=z.testzip();names=z.namelist()
        same=all(hashlib.sha256(z.read(n)).digest()==hashlib.sha256((stage_root/n).read_bytes()).digest() for n in names)
    digest=hashlib.sha256(zpath.read_bytes()).hexdigest()
    (out/(NAME+'.zip.sha256')).write_text(f'{digest}  {zpath.name}\n',encoding='ascii')
    exe_digest=hashlib.sha256((stage/'Tune.exe').read_bytes()).hexdigest()
    report['checks']['zip_integrity']={'result':'PASS' if bad is None and same else 'FAIL','entries':len(names)}
    report.update(zip=str(zpath),zip_sha256=digest,exe_sha256=exe_digest,zip_bytes=zpath.stat().st_size,entries=names)
    shutil.rmtree(stage_root)
    (out/(NAME+'-package-report.json')).write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in report.items() if k!='entries'},indent=2))

if __name__=='__main__':main(*sys.argv[1:])
